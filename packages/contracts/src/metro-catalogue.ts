/** A station on more than one line of the catalogue. */
export const metroInterchanges = (): Set<string> => {
  const seen = new Map<string, number>();
  for (const l of METRO_CATALOGUE) for (const s of l.stations) { const n = Array.isArray(s) ? s[0] : s; seen.set(n, (seen.get(n) ?? 0) + 1); }
  return new Set([...seen].filter(([, n]) => n > 1).map(([name]) => name));
};

